import { readFile, readdir } from "node:fs/promises";
import { randomBytes } from "node:crypto";
import { describe, expect, it, vi } from "vitest";
import { getSql } from "../db/client";
import { hashToken } from "../db/ids";
import { oauthCutoverReportInTransaction, revokeLegacyOAuthInTransaction } from "./oauth-cutover";
vi.mock("server-only", () => ({}));

describe.skipIf(!process.env.DATABASE_URL)("0029 cutover", () => {
  it("preserves three organisations, seven personal hives, 47 cells, snapshots and scoped keys through replay and safe rollback", async () => {
    const sql = getSql();
    const directory = new URL("../../../drizzle/", import.meta.url);
    const marker = new Error("fixture complete");
    await expect(sql.begin(async tx => {
      const schema = `cutover_${randomBytes(8).toString("hex")}`;
      await tx`CREATE SCHEMA ${tx(schema)}`;
      await tx`SET LOCAL search_path TO ${tx(schema)}`;
      await tx`CREATE TABLE _migrations (name text PRIMARY KEY)`;
      for (const name of (await readdir(directory)).filter(name => name.endsWith(".sql") && name < "0027" && name !== "0002_pgvector.sql").sort()) {
        let body = await readFile(new URL(name, directory), "utf8");
        if (name === "0015_slack.sql") body = body.replace(/DO \$\$ BEGIN\n IF EXISTS \(SELECT 1 FROM pg_type WHERE typname='vector'\)[\s\S]*?END \$\$;/, "");
        await tx.unsafe(body);
      }
      for (let n = 1; n <= 3; n++) await tx`INSERT INTO teams (id,name,invite_code) VALUES (${`org_${n}`}, ${`Organisation ${n}`}, ${hashToken(`org-${n}`)})`;
      for (let n = 1; n <= 7; n++) await tx`INSERT INTO members (id,name,email,email_verified,team_id,role) VALUES (${`human_${n}`}, ${`Human ${n}`}, ${`human${n}@example.test`}, true, ${`org_${(n - 1) % 3 + 1}`}, ${n <= 3 ? "admin" : "member"})`;
      for (let n = 1; n <= 47; n++) await tx`INSERT INTO learnings (id,member_id,team_id,title,body,kind,source,confidence) VALUES (${`cell_${n}`}, ${`human_${(n - 1) % 7 + 1}`}, ${`org_${((n - 1) % 7) % 3 + 1}`}, 'Existing cell', 'Existing body', 'learning', 'manual', 1)`;
      await tx`INSERT INTO api_keys (id,team_id,member_id,key_hash,prefix) VALUES ('key','org_1','human_1',${hashToken("fixture-key")},'fixture')`;
      await tx`INSERT INTO web_sessions (id,team_id,member_id,token_hash,expires_at) VALUES ('session','org_1','human_1',${hashToken("fixture-session")},now()+interval '1 day')`;
      await tx.unsafe(await readFile(new URL("0027_multi_hive.sql", directory), "utf8"));
      await tx.unsafe(await readFile(new URL("0028_project_sharing.sql", directory), "utf8"));
      await tx`INSERT INTO knowledge_snapshots (token_hash,member_id,team_id,revision,object_key,expires_at,audience_team_ids) VALUES ('snapshot','human_1','org_1',1,'fixture',now()+interval '1 day',ARRAY['org_1'])`;
      await tx`INSERT INTO auth_oauth_client (id,client_id,redirect_uris,scopes) VALUES ('client','client',ARRAY['http://localhost/callback'],ARRAY['hive'])`;
      await tx`INSERT INTO auth_oauth_consent (id,client_id,user_id,reference_id,scopes,created_at,updated_at) VALUES ('consent','client','human_1','org_1',ARRAY['hive'],now(),now())`;
      await tx`INSERT INTO auth_oauth_refresh_token (id,token,client_id,user_id,reference_id,scopes,created_at,expires_at) VALUES ('refresh','fixture','client','human_1','org_1',ARRAY['hive'],now(),now()+interval '1 day')`;
      await tx`INSERT INTO auth_oauth_consent (id,client_id,user_id,reference_id,scopes,created_at,updated_at) VALUES ('old-person-consent','client','human_1','team_personal_human_1',ARRAY['hive','hive:person'],now(),now())`;
      await tx`INSERT INTO auth_oauth_refresh_token (id,token,client_id,user_id,reference_id,scopes,created_at,expires_at) VALUES ('old-person-refresh','old-person','client','human_1','team_personal_human_1',ARRAY['hive','hive:person'],now(),now()+interval '1 day')`;
      const cells = await tx`SELECT to_jsonb(l) AS value FROM learnings l ORDER BY id`;
      const versions = await tx`SELECT to_jsonb(v) AS value FROM learning_versions v ORDER BY learning_id`;
      const snapshots = await tx`SELECT to_jsonb(s) AS value FROM knowledge_snapshots s`;
      const members = await tx`SELECT id,team_id,role,removed_at FROM members ORDER BY id`;
      const constraints = await tx`SELECT * FROM hive_identity_legacy_constraints ORDER BY table_name,constraint_name`;
      const up = await readFile(new URL("0029_multi_hive_cutover.sql", directory), "utf8");
      const down = await readFile(new URL("rollback/0029_multi_hive_cutover.sql", directory), "utf8");
      await tx.unsafe(up);
      const epoch = (await tx`SELECT value FROM auth_verification WHERE id='hive-oauth-cutover'`)[0].value;
      await tx.unsafe(up);
      expect((await tx`SELECT revoked FROM auth_oauth_refresh_token WHERE id='old-person-refresh'`)[0].revoked).toBeNull();
      expect((await tx`SELECT value FROM auth_verification WHERE id='hive-oauth-cutover'`)[0].value).toBe(epoch);
      expect(await tx`SELECT column_name FROM information_schema.columns WHERE table_schema=${schema} AND table_name='members' AND column_name IN ('team_id','role','removed_at')`).toHaveLength(0);
      expect((await tx`SELECT count(*)::int AS n FROM teams WHERE personal_owner_member_id IS NULL`)[0].n).toBe(3);
      expect((await tx`SELECT count(*)::int AS n FROM teams WHERE personal_owner_member_id IS NOT NULL`)[0].n).toBe(7);
      expect(await tx`SELECT to_jsonb(l) AS value FROM learnings l ORDER BY id`).toEqual(cells);
      expect(await tx`SELECT to_jsonb(v) AS value FROM learning_versions v ORDER BY learning_id`).toEqual(versions);
      expect(await tx`SELECT to_jsonb(s) AS value FROM knowledge_snapshots s`).toEqual(snapshots);
      expect((await tx`SELECT revoked FROM auth_oauth_refresh_token WHERE id='refresh'`)[0].revoked).toBeNull();
      expect(await tx`SELECT id FROM auth_oauth_consent`).toHaveLength(2);
      expect((await tx`SELECT revoked_at FROM api_keys WHERE id='key'`)[0].revoked_at).toBeNull();
      expect((await tx`SELECT token_hash FROM web_sessions WHERE id='session'`)[0].token_hash).toBe(hashToken("fixture-session"));
      await tx`INSERT INTO hive_memberships (member_id,team_id) VALUES ('human_1','org_2')`;
      await expect(tx.savepoint(sp => sp.unsafe(down))).rejects.toThrow(/Refuse lossy/);
      await tx`DELETE FROM hive_memberships WHERE member_id='human_1' AND team_id='org_2'`;
      await tx`INSERT INTO auth_oauth_consent (id,client_id,user_id,reference_id,scopes,created_at,updated_at) VALUES ('new-consent','client','human_1','team_personal_human_1',ARRAY['hive','hive:person'],clock_timestamp(),clock_timestamp())`;
      await expect(tx.savepoint(sp => sp.unsafe(down))).rejects.toThrow(/Refuse lossy/);
      await tx`DELETE FROM auth_oauth_consent WHERE id='new-consent'`;
      await tx.unsafe(down);
      expect(await tx`SELECT id,team_id,role,removed_at FROM members ORDER BY id`).toEqual(members);
      expect(await tx`SELECT * FROM hive_identity_legacy_constraints ORDER BY table_name,constraint_name`).toEqual(constraints);
      expect((await tx`SELECT revoked FROM auth_oauth_refresh_token WHERE id='refresh'`)[0].revoked).toBeNull();
      await tx.unsafe(up);
      await tx`UPDATE members SET name='Changed name' WHERE id='human_1'`;
      expect(await tx`SELECT token_hash FROM knowledge_snapshots`).toHaveLength(0);
      const grantsBefore = await tx`SELECT to_jsonb(r) AS value FROM auth_oauth_refresh_token r ORDER BY id`;
      const report = await oauthCutoverReportInTransaction(tx);
      expect(report.totals).toEqual({ access: 0, refresh: 2, consent: 2 });
      expect(report.people[0]).toMatchObject({ memberId: 'human_1', refresh: 2, consent: 2 });
      expect(await tx`SELECT to_jsonb(r) AS value FROM auth_oauth_refresh_token r ORDER BY id`).toEqual(grantsBefore);
      await expect(tx.savepoint(sp => revokeLegacyOAuthInTransaction(sp, 'unapproved'))).rejects.toThrow(/Grants changed/);
      expect(await tx`SELECT to_jsonb(r) AS value FROM auth_oauth_refresh_token r ORDER BY id`).toEqual(grantsBefore);
      await revokeLegacyOAuthInTransaction(tx, report.digest);
      expect(await tx`SELECT id FROM auth_oauth_refresh_token WHERE revoked IS NULL`).toHaveLength(0);
      expect(await tx`SELECT id FROM auth_oauth_consent`).toHaveLength(0);
      expect(Number((await tx`SELECT value FROM auth_verification WHERE id='hive-oauth-cutover'`)[0].value)).toBeGreaterThan(0);
      await expect(tx.savepoint(sp => sp.unsafe(down))).rejects.toThrow(/Refuse lossy/);
      await expect(tx.savepoint(sp => revokeLegacyOAuthInTransaction(sp, report.digest))).rejects.toThrow(/already run/);
      await tx`INSERT INTO auth_oauth_refresh_token (id,token,client_id,user_id,reference_id,scopes,created_at,expires_at) VALUES ('new-refresh','new-refresh','client','human_1','team_personal_human_1',ARRAY['hive','hive:person'],clock_timestamp(),now()+interval '1 day')`;
      await tx.unsafe(up);
      expect((await tx`SELECT revoked FROM auth_oauth_refresh_token WHERE id='new-refresh'`)[0].revoked).toBeNull();
      throw marker;
    })).rejects.toBe(marker);
  });
});
